def fit_cheby_leastsq(order, mass, dataset, label, nbins=100):
    h = ROOT.TH1F(f'h_{label}_{order}', '', nbins, mass.getMin(), mass.getMax())
    dataset.fillHistogram(h, ROOT.RooArgList(mass))

    coeffs = [
        ROOT.RooRealVar(f'c{label}{i}', f'c{label}{i}', 0, -1, 1)
        for i in range(1, order + 1)
    ]

    pdf = ROOT.RooChebychev(
        f'bkg_cheby_{label}_{order}',
        f'bkg_cheby_{label}_{order}',
        mass,
        ROOT.RooArgList(*coeffs)
    )

    dh = ROOT.RooDataHist(
        f'dh_{label}_{order}', '',
        ROOT.RooArgList(mass), h
    )

    res = pdf.chi2FitTo(
        dh,
        ROOT.RooFit.Range('left,right'),
        ROOT.RooFit.Save()
    )

    sse = res.minNll()

    n_fit_bins = 0
    for i in range(1, nbins + 1):
        x = h.GetBinCenter(i)
        if fit_range_lo <= x <= mass_window_lo or mass_window_hi <= x <= fit_range_hi:
            n_fit_bins += 1

    ndf = n_fit_bins - order

    return pdf, coeffs, res, sse, ndf


