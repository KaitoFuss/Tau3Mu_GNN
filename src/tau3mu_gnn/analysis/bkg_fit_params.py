    print(f"Order {order}: SSE = {sse:.4f}, NDF = {ndf}")

    if prev_sse is not None:
        # F-statistic: (SSE1 - SSE2) / (ndf1 - ndf2) / (SSE2 / ndf2)
        delta_sse = prev_sse - sse
        delta_ndf = prev_ndf - ndf  # = 1
        f_stat = (delta_sse / delta_ndf) / (sse / ndf)
        from scipy.stats import f as f_dist
        p_value = 1 - f_dist.cdf(f_stat, delta_ndf, ndf)
        print(f"  F-test vs order {order-1}: F={f_stat:.4f}, p={p_value:.4f}")
        if p_value < 0.05:
            best_order  = order
            prev_pdf    = pdf
            prev_coeffs = coeffs
